/**
 * Search airports by name, ICAO, IATA, city, or country.
 */
export function searchAirports(query: string): Airport[] {
  const q = query.trim().toUpperCase();
  if (!q) return WORLD_AIRPORTS.slice(0, 10);

  return WORLD_AIRPORTS.filter((a) => {
    return (
      a.iata.toUpperCase().includes(q) ||
      a.icao.toUpperCase().includes(q) ||
      a.name.toUpperCase().includes(q) ||
      a.city.toUpperCase().includes(q) ||
      a.country.toUpperCase().includes(q)
    );
  });
}
